"""Animated photo explainers for the service pages (one per service).

Each scene uses the standard 15-second timeline:
  0    intro    what the part is
  2.5  problem  what goes wrong (camera moves in)
  5.5  effect   what the owner notices
  8    cause    zoom bubble: the worn part
  11   fix      bubble switches to the new part
  13   result   check mark
Coordinates are stage units (1200 x 750). AI photos fill the stage; real photos are noted in the title.
"""

PH = "/photos/explainers/"
SV = "/photos/services/"
T = [0, 2.5, 5.5, 8, 11, 13]


def scene(slug, *, photo, heading, title, anchor, diagram, tags, labels, captions,
          zoom=1.35, focus=None, bubble=None, extra=(), check=None, real=False):
    ax, ay = anchor
    fx, fy = focus or anchor
    left = ax > 700
    dx = -60 if left else 60
    bx, by = bubble or ((250 if ax > 600 else 950), 290)
    fxs = [
        {"type": "ring", "x": ax, "y": ay, "r": 24, "tone": "white", "t": [0.4, 2.5]},
        {"type": "label", "x": ax, "y": ay, "text": labels[0], "tone": "navy", "dx": dx, "dy": -60, "t": [0.5, 2.5]},
        {"type": "ring", "x": ax, "y": ay, "r": 24, "tone": "red", "t": [2.5, 11]},
        {"type": "label", "x": ax, "y": ay, "text": labels[1], "tone": "red", "dx": dx, "dy": -60, "t": [2.7, 7.8]},
        *extra,
        {"type": "ring", "x": ax, "y": ay, "r": 24, "tone": "green", "t": [11, 14.2]},
        {"type": "label", "x": ax, "y": ay, "text": labels[2], "tone": "green", "dx": dx, "dy": -60, "t": [11.2, 14.6]},
        {"type": "check", "x": (check or (ax + (-90 if left else 90), ay - 120))[0],
         "y": (check or (ax, ay - 120))[1], "t": [13, 15.5]},
    ]
    cfg = {
        "photo": {"src": photo, "x": 0, "w": 1200},
        "title": [title, "Real job · Toronto" if real else "Window Repair GTA"],
        "cam": [[0, 1, 600, 375], [2.5, 1, 600, 375], [3.4, zoom, fx, fy], [10.4, zoom, fx, fy],
                [11.3, 1, 600, 375], [15, 1, 600, 375]],
        "fx": fxs,
        "bubble": {"x": bx, "y": by, "r": 140, "anchor": [ax, ay], "t": [7.8, 15.6],
                   "states": [{"t": 0, "diagram": diagram, "tag": tags[0], "tone": "red"},
                              {"t": 11, "diagram": diagram, "fixed": True, "tag": tags[1], "tone": "green"}]},
    }
    return slug, {"scene": slug, "render": "photo", "duration": 15, "heading": heading,
                  "steps": list(zip(T, captions)), "config": cfg}


def air(d, t=(5.5, 10.8)):
    return {"type": "flow", "d": d, "tone": "blue", "n": 14, "r": 5, "speed": 0.35, "t": list(t)}


def water(d, t=(5.5, 10.8)):
    return {"type": "flow", "d": d, "tone": "blue", "n": 10, "drop": True, "speed": 0.45, "t": list(t)}


